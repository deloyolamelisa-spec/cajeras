export function buildInitialHorarios(
  sucursales: Sucursal[] = INITIAL_SUCURSALES
): HorarioSucursalDia[] {
  const dias: DiaSemana[] = [
    'lunes',
    'martes',
    'miercoles',
    'jueves',
    'viernes',
    'sabado',
    'domingo',
  ];
  const result: HorarioSucursalDia[] = [];

  for (const suc of sucursales) {
    for (const dia of dias) {
      const esDomingo = dia === 'domingo';
      const esSabado = dia === 'sabado';
      result.push({
        id: `hor-${suc.id}-${dia}`,
        sucursal_id: suc.id,
        dia,
        hora_limite_actividad: esSabado ? '10:00' : '09:00',
        hora_limite_corte: esSabado ? '14:00' : '18:30',
        sin_horario_limite: esDomingo || (suc.id === 'suc-sur' && esSabado),
      });
    }
  }
  return result;
}
